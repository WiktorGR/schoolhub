class PasswordsController < ApplicationController
  allow_unauthenticated_access
  before_action :set_user_by_token, only: %i[ edit update ]
  rate_limit to: 10, within: 3.minutes, only: :create, with: -> { redirect_to new_password_path, alert: "Zbyt wiele prób. Spróbuj ponownie za kilka minut." }

  def new
  end

  def create
    if user = User.find_by(email_address: params[:email_address])
      PasswordsMailer.reset(user).deliver_later
    end

    redirect_to new_session_path, notice: "Jeśli konto z tym adresem istnieje, wysłaliśmy na nie instrukcję resetu hasła."
  end

  def edit
  end

  def update
    if @user.update(params.permit(:password, :password_confirmation))
      @user.sessions.destroy_all
      redirect_to new_session_path, notice: "Hasło zostało zmienione. Możesz się zalogować."
    else
      redirect_to edit_password_path(params[:token]), alert: "Hasła nie są takie same."
    end
  end

  private
    def set_user_by_token
      @user = User.find_by_password_reset_token!(params[:token])
    rescue ActiveSupport::MessageVerifier::InvalidSignature
      redirect_to new_password_path, alert: "Link do resetu hasła jest nieprawidłowy lub wygasł."
    end
end
